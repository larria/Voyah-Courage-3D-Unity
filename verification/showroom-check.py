import functools, http.server, threading, json
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / '.publish/showroom-verification'
OUT.mkdir(parents=True, exist_ok=True)
server = http.server.ThreadingHTTPServer(('127.0.0.1', 0), functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(ROOT)))
threading.Thread(target=server.serve_forever, daemon=True).start()
url = f'http://127.0.0.1:{server.server_port}/'
results = {'url': url, 'steps': [], 'errors': []}
with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page(viewport={'width': 1440, 'height': 1000}, device_scale_factor=1)
    page.on('pageerror', lambda error: results['errors'].append(str(error)))
    page.goto(url)
    page.screenshot(path=str(OUT / 'loading.png'))
    page.wait_for_function("window.car?.getState().lifecycle === 'ready'", timeout=240000)
    page.wait_for_timeout(2000)
    page.screenshot(path=str(OUT / 'desktop.png'))
    results['steps'].append({'ready': page.locator('#loading').is_hidden(), 'canvas': page.locator('canvas').count()})
    def click(selector):
        page.locator(selector).click()
        page.wait_for_function("!document.querySelector('[data-method][aria-busy=true]')", timeout=60000)
        page.wait_for_timeout(500)
    click('[data-method=setPaint][data-value=\'"NUB"\']')
    click('[data-method=enterInterior]')
    page.wait_for_timeout(2000)
    page.screenshot(path=str(OUT / 'interior.png'))
    click('[data-method=exitInterior]')
    page.locator('[data-tab=openings]').click()
    click('[aria-label="左前车门：打开"]')
    click('[aria-label="左前车门：关闭"]')
    click('[aria-label="左前车窗：降下"]')
    click('[aria-label="左前车窗：升起"]')
    click('[data-method=toggleTrunk]')
    click('[data-method=toggleTrunk]')
    page.locator('[data-tab=experience]').click()
    for label in ['前大灯：开启', '前大灯：关闭', '后视镜：折叠', '后视镜：展开', '锁车演示：锁车', '锁车演示：解锁', '充电流光：开启', '充电流光：关闭']:
        click(f'[aria-label="{label}"]')
        page.wait_for_timeout(3000)
    results['steps'].append({'controls': page.evaluate('window.car.getState()')})
    page.locator('#immerse').click()
    page.wait_for_timeout(500)
    page.screenshot(path=str(OUT / 'immersive.png'))
    results['steps'].append({'immersive': page.evaluate("document.querySelector('#stage').getBoundingClientRect().width === innerWidth")})
    results['steps'].append({'fullscreen': page.evaluate('!!document.fullscreenElement')})
    page.locator('#restore').click()
    results['steps'].append({'restored': page.evaluate('!document.fullscreenElement && !document.querySelector("#showroom").classList.contains("immersive")')})
    page.set_viewport_size({'width': 390, 'height': 844})
    page.locator('[data-tab=design]').click()
    page.wait_for_timeout(1000)
    page.screenshot(path=str(OUT / 'mobile.png'))
    results['steps'].append({'mobileOverflow': page.evaluate('document.documentElement.scrollWidth > innerWidth')})
    page.close()
    failure = browser.new_page(viewport={'width': 1000, 'height': 800})
    failure.route('**/ZY.loader.js', lambda route: route.abort())
    failure.goto(url)
    failure.locator('#retry').wait_for(state='visible', timeout=15000)
    failure.screenshot(path=str(OUT / 'failure.png'))
    failure.unroute('**/ZY.loader.js')
    failure.locator('#retry').click()
    failure.wait_for_function("window.car?.getState().lifecycle === 'ready'", timeout=240000)
    results['steps'].append({'retryReady': failure.locator('#loading').is_hidden(), 'canvasAfterRetry': failure.locator('canvas').count()})
    failure.screenshot(path=str(OUT / 'retry.png'))
    browser.close()
server.shutdown()
(OUT / 'results.json').write_text(json.dumps(results, ensure_ascii=False, indent=2))
print(json.dumps(results, ensure_ascii=False, indent=2))
